export function getTypeMultiplier(atkType: PokemonType, defType: PokemonType, secondaryDefType?: PokemonType): number {
  const chartRow = TYPE_CHART[atkType];
  const primaryMult = chartRow?.[defType] ?? 1.0;
  let secondaryMult = 1.0;
  if (secondaryDefType) {
    secondaryMult = chartRow?.[secondaryDefType] ?? 1.0;
  }
  return primaryMult * secondaryMult;
}

